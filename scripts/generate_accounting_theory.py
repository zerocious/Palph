def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    fc_lines = [
        "# Бухучёт — теоретические вопросы (2 курс)",
        "# Формат: вопрос || экзаменационный ответ || topics",
        "# Источник: study_materials/accounting/source/Теоретические-вопросы-2-курс.txt",
        "# Подсказки (краткие) — в theory-with-hints.txt",
        "",
    ]
    hint_lines = [
        "# Бухучёт — теоретические вопросы с подсказками",
        "# Формат: вопрос || полный ответ ## краткая подсказка",
        "# Подсказка показывается при ошибке (формат user_tasks); для самопроверки.",
        "# Источник: study_materials/accounting/source/",
        "",
    ]

    for i, (title, question, definition, hint, topic) in enumerate(ITEMS, start=1):
        term = f"[{i}] {question}"
        fc_lines.append(f"{term} || {definition} || {topic}")
        hint_lines.append(f"{term} || {definition} ## {hint}")

    (OUT_DIR / "flashcards.txt").write_text("\n".join(fc_lines) + "\n", encoding="utf-8")
    (OUT_DIR / "theory-with-hints.txt").write_text("\n".join(hint_lines) + "\n", encoding="utf-8")

    print(f"Generated {len(ITEMS)} Q&A pairs")
    print(f"  {OUT_DIR / 'flashcards.txt'}")
    print(f"  {OUT_DIR / 'theory-with-hints.txt'}")


if __name__ == "__main__":
    main()
