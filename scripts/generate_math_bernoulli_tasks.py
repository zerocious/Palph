def main() -> None:
    tasks_dir = ROOT / "tasks"
    diag_dir = ROOT / "diagnostic"
    tasks_dir.mkdir(parents=True, exist_ok=True)
    diag_dir.mkdir(parents=True, exist_ok=True)

    groups = {
        GROUP: {
            "title": "Билет — задача 1 (формула Бернулли)",
            "description": "Точная формула Бернулли для малого числа испытаний",
        }
    }
    with open(ROOT / "groups.json", "w", encoding="utf-8") as f:
        json.dump(groups, f, ensure_ascii=False, indent=2)

    with open(ROOT / "topics.json", "w", encoding="utf-8") as f:
        json.dump({"order": TOPIC}, f, ensure_ascii=False, indent=2)

    for spec in TASKS:
        payload = {**COMMON, **{k: v for k, v in spec.items() if k != "id"}}
        path = tasks_dir / f"{spec['id']}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(payload, f, ensure_ascii=False, indent=2)

    with open(diag_dir / "default.json", "w", encoding="utf-8") as f:
        json.dump(DIAGNOSTIC, f, ensure_ascii=False, indent=2)

    print(f"Wrote {len(TASKS)} tasks to {tasks_dir}")


if __name__ == "__main__":
    main()
